#!/usr/bin/env Rscript
lib_path <- Sys.getenv("RERUN_R_LIB", "/bigdata/godziklab/shared/Xinru/R")
.libPaths(c(lib_path, .libPaths()))
if (nzchar(Sys.getenv("RERUN_R_LIB"))) {
  .rerun_r_lib_resolved <- normalizePath(.libPaths()[1], mustWork = FALSE)
  .rerun_r_lib_expected <- normalizePath(Sys.getenv("RERUN_R_LIB"), mustWork = FALSE)
  if (!identical(.rerun_r_lib_resolved, .rerun_r_lib_expected)) {
    stop(sprintf(
      "RERUN_R_LIB audit guard: .libPaths()[1] resolved to '%s' but RERUN_R_LIB='%s' -- the shared/legacy library would take precedence over the pinned isolated library. Refusing to proceed.",
      .rerun_r_lib_resolved, .rerun_r_lib_expected))
  }
  cat("=== Pinned R environment audit guard ===\n")
  cat("R.version.string:", R.version.string, "\n")
  cat("RERUN_R_LIB:", Sys.getenv("RERUN_R_LIB"), "\n")
  cat("CMDSTAN:", Sys.getenv("CMDSTAN"), "\n")
  cat(".libPaths():\n")
  print(.libPaths())
  cat("=========================================\n")
}

# ==============================================================================
# 32_fig2J_pseudotime_heatmap.R
# Fig 2J: Gene expression dynamics along Monocle3 pseudotime trajectory
# Heatmap of pseudotime-dependent genes (graph_test/Moran's I, q<0.05),
# hierarchically clustered into modules, ordered by pseudotime (BM + Blood + C0-C5)
#
# Input:  $BASE/monocle_threeway/monocle3_threeway_cds.rds
#         (must be regenerated by the align_cds()-fixed 11b_monocle3_integrated.R
#         so it loads cleanly under the current monocle3 version)
# Output: revision/figures/fig2/fig2J_pseudotime_heatmap.pdf
# SLURM:  batch, 64G, 4 CPUs, 8h (graph_test over many genes is much slower
#         than the raw-variance ranking this replaces)
# ==============================================================================

suppressPackageStartupMessages({
  library(Matrix)
  library(pheatmap)
  library(dplyr)
  library(monocle3)
})

SCRIPTS <- dirname(sub("--file=", "", grep("--file=", commandArgs(trailingOnly = FALSE), value = TRUE)[1]))
if (is.na(SCRIPTS) || SCRIPTS == "") {
  SCRIPTS <- "/bigdata/nairlab/shared/XQiu/EOS_project/adipose-eos-subtype-atlas/scripts"
}
source(file.path(SCRIPTS, "00_theme.R"))

BASE <- "/bigdata/nairlab/shared/XQiu/EOS_project/PNAS_revision/atlas"
PNAS <- "/bigdata/nairlab/shared/XQiu/EOS_project/PNAS_revision"
out_dir <- file.path(PNAS, "revision/figures/fig2")
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

# --- Group colors (for annotation) -------------------------------------------
group_colors <- c(
  "Gurtner BM"    = "#2E8B57",
  "C3"            = "#CBAACB",
  "Gurtner Blood" = "#DAA520",
  "C1"            = "#E84A5F",
  "C5"            = "#5BA4A4",
  "C4"            = "#B03A48",
  "C0"            = "#6CA6CD",
  "C2"            = "#FF6F1F"
)

# =============================================================================
# 1. Load Monocle3 three-way CDS
# =============================================================================
cat("Loading monocle3_threeway_cds.rds ...\n")

# Loaded normally (via monocle3's own S4 classes) rather than the previous
# low-level unserialize workaround, which existed specifically to avoid
# triggering monocle3 dispatch and therefore made calling graph_test() on this
# object impossible. The object must come from the current monocle3 version
# (regenerate via 11b_monocle3_integrated.R if this readRDS() errors on class
# validity).
rds_path <- file.path(BASE, "monocle_threeway", "monocle3_threeway_cds.rds")
cds <- readRDS(rds_path)
cat(sprintf("  %d cells x %d genes\n", ncol(cds), nrow(cds)))

pt_all <- pseudotime(cds)
if (!any(is.finite(pt_all))) {
  stop("Cannot find pseudotime. Check that order_cells() was run on this CDS.")
}
cat(sprintf("  Pseudotime range: %.1f - %.1f\n",
            min(pt_all[is.finite(pt_all)]), max(pt_all[is.finite(pt_all)])))

# =============================================================================
# 2. Subset to main figure groups (BM + Blood + C0-C5)
# =============================================================================
cat("Subsetting to main groups ...\n")
main_groups <- c("Gurtner BM", "Gurtner Blood",
                 "C0", "C1", "C2", "C3", "C4", "C5")
grp <- colData(cds)$main_group
keep <- !is.na(grp) & grp %in% main_groups & is.finite(pt_all)
cds_main <- cds[, keep]
meta_main <- as.data.frame(colData(cds_main))
pt <- pt_all[keep]
cat(sprintf("  Main group cells with finite pseudotime: %d\n", sum(keep)))

# =============================================================================
# 3. Identify pseudotime-dependent genes via graph_test() (Moran's I)
# =============================================================================
cat("Running graph_test() (Moran's I) on the principal graph ...\n")

gene_test_res <- graph_test(cds_main, neighbor_graph = "principal_graph", cores = 4)
gene_test_res <- gene_test_res[!is.na(gene_test_res$q_value), ]
sig_genes <- rownames(gene_test_res)[gene_test_res$q_value < 0.05]
if (length(sig_genes) == 0) {
  stop("No genes reached q_value < 0.05 in graph_test(); nothing to plot.")
}
# Rank by Moran's I (strength of the pseudotime-associated pattern)
sig_genes <- sig_genes[order(gene_test_res[sig_genes, "morans_I"], decreasing = TRUE)]
cat(sprintf("  Genes significant at q < 0.05: %d\n", length(sig_genes)))

# Normalized expression (library-size + log1p) for the significant gene set
counts_main <- as.matrix(counts(cds_main))
lib_sizes <- colSums(counts_main)
norm_mat <- log1p(t(t(counts_main) / lib_sizes * 1e4))

# =============================================================================
# 4. Order cells by pseudotime and bin for visualization
# =============================================================================
cat("Ordering cells and binning ...\n")

# Order cells by pseudotime
cell_order <- order(pt)
pt_ordered <- pt[cell_order]
groups_ordered <- as.character(meta_main$main_group)[cell_order]

# Bin cells into 200 bins along pseudotime for cleaner visualization
n_bins <- 200
bin_idx <- cut(seq_along(pt_ordered), breaks = n_bins, labels = FALSE)

# Average expression per bin
norm_ordered <- norm_mat[sig_genes, cell_order]
bin_mat <- sapply(1:n_bins, function(b) {
  cells_in_bin <- which(bin_idx == b)
  if (length(cells_in_bin) == 1) {
    norm_ordered[, cells_in_bin]
  } else {
    rowMeans(norm_ordered[, cells_in_bin, drop = FALSE])
  }
})
colnames(bin_mat) <- paste0("bin_", 1:n_bins)

# Bin pseudotime (mean per bin) and majority group per bin
bin_pt <- tapply(pt_ordered, bin_idx, mean)
bin_group <- tapply(groups_ordered, bin_idx, function(x) {
  tab <- table(x)
  names(tab)[which.max(tab)]
})

cat(sprintf("  Binned into %d pseudotime bins\n", n_bins))

# =============================================================================
# 5. Scale genes (z-score across bins)
# =============================================================================
cat("Scaling gene expression ...\n")
bin_scaled <- t(scale(t(bin_mat)))
bin_scaled[bin_scaled > 2.5] <- 2.5
bin_scaled[bin_scaled < -2.5] <- -2.5
bin_scaled[is.na(bin_scaled)] <- 0

# =============================================================================
# 6. Cluster genes by expression pattern (hierarchical clustering)
# =============================================================================
cat("Clustering genes ...\n")
k <- 6  # number of gene clusters
gene_dist <- dist(bin_scaled, method = "euclidean")
hc <- hclust(gene_dist, method = "complete")
gene_cluster <- cutree(hc, k = k)

# Order gene clusters by peak pseudotime position
cluster_peak <- sapply(1:k, function(cl) {
  genes_cl <- names(gene_cluster[gene_cluster == cl])
  mean_expr <- colMeans(bin_scaled[genes_cl, , drop = FALSE])
  which.max(mean_expr)
})
cluster_order <- order(cluster_peak)

# Reorder genes: within each cluster, sort by peak position
gene_order <- c()
gene_clusters <- c()
for (cl in cluster_order) {
  genes_cl <- names(gene_cluster[gene_cluster == cl])
  peaks <- apply(bin_scaled[genes_cl, , drop = FALSE], 1, which.max)
  genes_sorted <- genes_cl[order(peaks)]
  gene_order <- c(gene_order, genes_sorted)
  gene_clusters <- c(gene_clusters, rep(cl, length(genes_sorted)))
}

bin_scaled_ordered <- bin_scaled[gene_order, ]
cat(sprintf("  %d genes in %d clusters\n", length(gene_order), k))

# =============================================================================
# 7. Build annotation data frames
# =============================================================================

# Column annotation: pseudotime group (majority per bin)
col_anno <- data.frame(
  Group = factor(bin_group, levels = names(group_colors)),
  row.names = colnames(bin_scaled_ordered)
)

# Row annotation: label each gene cluster by top genes + functional description
module_numbers <- match(gene_clusters, cluster_order)

# Get top 3 genes per module by variance across pseudotime bins (not peak
# height -- the previous `max` ranking favored genes with one large spike over
# genes that vary consistently across the module's pseudotime window)
module_top_genes <- character(k)
for (m in 1:k) {
  genes_m <- gene_order[module_numbers == m]
  gene_var <- apply(bin_scaled_ordered[genes_m, , drop = FALSE], 1, var)
  top3 <- head(names(sort(gene_var, decreasing = TRUE)), 3)
  module_top_genes[m] <- paste(top3, collapse = "/")
}

# Functional labels combining genes + biology
module_func_labels <- c(
  paste0(module_top_genes[1], "\nRNA splicing &\ngranule biogenesis"),
  paste0(module_top_genes[2], "\nEffector granule\nloading & RNA stability"),
  paste0(module_top_genes[3], "\nTranscriptional control\n& adhesion/migration"),
  paste0(module_top_genes[4], "\nECM interaction &\nmembrane dynamics"),
  paste0(module_top_genes[5], "\nStress signaling &\nantimicrobial transport"),
  paste0(module_top_genes[6], "\nMetabolic adaptation\n& bioenergetics")
)

cat("  Gene cluster labels:\n")
for (m in 1:k) cat(sprintf("    Cluster %d: %s\n", m, module_top_genes[m]))

gene_cluster_labels <- module_func_labels[module_numbers]
row_anno <- data.frame(
  Module = factor(gene_cluster_labels, levels = module_func_labels),
  row.names = gene_order
)

# Annotation colors
module_palette <- c("#E41A1C", "#377EB8", "#4DAF4A", "#984EA3", "#FF7F00", "#A65628")
names(module_palette) <- module_func_labels

anno_colors <- list(
  Group = group_colors,
  Module = module_palette
)

# =============================================================================
# 8. Plot heatmap
# =============================================================================
cat("Generating heatmap ...\n")

heatmap_colors <- colorRampPalette(c("#2166AC", "#4393C3", "#92C5DE",
                                     "#F7F7F7",
                                     "#FDDBC7", "#F4A582", "#B2182B"))(100)

# Gaps between gene clusters
cluster_sizes <- table(factor(gene_cluster_labels, levels = module_func_labels))
row_gaps <- cumsum(cluster_sizes)[-length(cluster_sizes)]

pdf_path <- file.path(out_dir, "fig2J_pseudotime_heatmap.pdf")
cairo_pdf(pdf_path, width = 12, height = 12)
pheatmap(bin_scaled_ordered,
         cluster_rows = FALSE,
         cluster_cols = FALSE,
         show_rownames = FALSE,
         show_colnames = FALSE,
         color = heatmap_colors,
         breaks = seq(-2.5, 2.5, length.out = 101),
         annotation_col = col_anno,
         annotation_row = row_anno,
         annotation_colors = anno_colors,
         gaps_row = row_gaps,
         border_color = NA,
         main = "Gene Expression Dynamics Along Pseudotime",
         fontsize = 10,
         annotation_names_col = TRUE,
         annotation_names_row = TRUE,
         annotation_legend = TRUE)
dev.off()
cat(sprintf("  Saved: %s\n", pdf_path))

# =============================================================================
# 9. Export gene lists per module
# =============================================================================
cat("Exporting gene module lists ...\n")
module_df <- data.frame(
  gene = gene_order,
  module = gene_cluster_labels,
  peak_bin = apply(bin_scaled_ordered, 1, which.max),
  peak_pseudotime = bin_pt[apply(bin_scaled_ordered, 1, which.max)],
  stringsAsFactors = FALSE
)
write.csv(module_df, file.path(out_dir, "fig2J_gene_modules.csv"), row.names = FALSE)

# Summary
cat("\nGene module summary:\n")
for (m in module_func_labels) {
  genes_m <- module_df$gene[module_df$module == m]
  m_short <- gsub("\n", " ", m)
  cat(sprintf("  %s: %d genes, median peak pseudotime = %.1f\n",
              m_short, length(genes_m), median(module_df$peak_pseudotime[module_df$module == m])))
}

cat(sprintf("\nDone! Fig 2J saved to: %s\n", out_dir))
